import { readFile, writeFile } from 'node:fs/promises';
import { gameLoopMarkup } from '../site/assets/game.js';

const path = new URL('../site/assets/living-room.svg', import.meta.url);
const before = await readFile(path, 'utf8');
const start = '<!-- Shared game: generated by scripts/update-website-game.mjs. -->';
const end = '<!-- /Shared game -->';
const content = `${start}\n    <svg x="284" y="111" width="370" height="190" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice" stroke="none">${gameLoopMarkup('hero-game')}</svg>\n    ${end}`;
const after = before.replace(new RegExp(`${start}[\\s\\S]*?${end}`), content);
if (!before.includes(start) || !before.includes(end)) throw new Error('Missing hero game markers');
if (process.argv.includes('--check')) {
  if (before !== after) throw new Error('Run node scripts/update-website-game.mjs to refresh the hero game');
} else if (before !== after) await writeFile(path, after);
